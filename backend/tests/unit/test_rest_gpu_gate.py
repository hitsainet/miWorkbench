def test_no_route_has_colliding_names():
    """`_method` and `_route` are reserved, and a gated route's path, query and body names never collide. R1 review
    fix (OR1-045a0-10), 2026-11-16: the body names are the route's DECLARED fields (the model's fields and aliases;
    an embedded route's parameter names), not the sample request's keys, so an optional field the sample leaves out
    is checked too."""
    from src.core.approval_gate import _declared_keys, _embed, _flat, iter_routes
    from src.core.approval_payload import RESERVED_KEYS

    routes = {path: route for path, route in iter_routes(_app()) if "POST" in route.methods}
    for row in GATED_ROWS:
        path, _ = DESIGN[row]
        route = routes[path]
        flat = _flat(route)
        outside = [p.alias for p in flat.query_params] + [p.name for p in route.dependant.path_params]
        body: set[str] = set()
        if _embed(route):
            body = {p.alias for p in flat.body_params} | {p.name for p in flat.body_params}
        elif flat.body_params:
            body = set(_declared_keys(flat.body_params[0].field_info.annotation) or {})
        assert not (set(outside) | body) & RESERVED_KEYS, (row, outside, sorted(body))
        assert len(outside) == len(set(outside)), (row, outside)
        assert not set(outside) & body, (row, sorted(set(outside) & body))


