def _other_call(req):
    """The same route called with ONE different value: a path parameter when the route has one, else a top-level
    string of the body. `None` when the body has neither (recorded per row)."""
    if req["path_params"]:
        name, value = next(iter(req["path_params"].items()))
        return {"path": req["path"].replace(value, value + "_other"), "body": req["body"]}
    if isinstance(req["body"], dict):
        for key, value in req["body"].items():
            if isinstance(value, str):
                return {"path": req["path"], "body": {**req["body"], key: value + "_other"}}
    return None


