def _declares(row, key) -> bool:
    from src.core.approval_gate import _flat, iter_routes

    path, _ = DESIGN[row]
    route = {p: r for p, r in iter_routes(_app()) if "POST" in r.methods}[path]
    from pydantic import BaseModel

    for param in _flat(route).body_params:
        ann = param.field_info.annotation
        if isinstance(ann, type) and issubclass(ann, BaseModel) and key in ann.model_fields:
            return True
    return False


