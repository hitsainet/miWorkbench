def build_vectors(app) -> dict:
    from src.core.approval_gate import body_param_name, iter_routes
    from src.core.approval_payload import canonical_payload

    routes = {path: route for path, route in iter_routes(app) if "POST" in route.methods}
    vectors = []
    for row in GATED_ROWS:
        path, action = DESIGN[row]
        req = sample_request(app, row)
        payload = canonical_payload("POST", path, req["path_params"], req["query"], req["body"],
                                    body_param=body_param_name(routes[path]))
        vectors.append({"row": str(row), "action": action, "method": "POST", "route": path,
                        "request": {"path": req["path"], "query": req["query"], "body": req["body"]},
                        "payload": payload})
    return {"kind": "miworkbench.approval-payload-vectors/v1",
            "note": "One vector per gated route (045 FR-13; A29, A38): the request an agent sends and the flat "
                    "canonical payload the operator approves. Generated by backend/tests/unit/test_rest_gpu_gate.py "
                    "(WRITE_APPROVAL_VECTORS=1); do not edit by hand.",
            "vectors": vectors}


